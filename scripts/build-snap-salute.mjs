/** Bake original authored wrist/pole targets into ordinary bounded pose curves.
 * IK is an authoring operation only; the runtime samples compact quaternions.
 */
import fs from "node:fs/promises";
import { Quaternion, Euler, Vector3 } from "three";
const root = new URL("../", import.meta.url);
const source = JSON.parse(
  await fs.readFile(
    new URL("assets/source/performances/snap-salute/keyframes.json", root),
    "utf8",
  ),
);
const catalog = JSON.parse(
  await fs.readFile(new URL("public/catalog.json", root), "utf8"),
);
const sockets = new Map(
  catalog.rig.sockets.map((socket) => [socket.id, socket]),
);
const bones = catalog.rig.sockets
  .map((socket) => socket.id)
  .filter((name) => name !== "root");
const v = (values) => new Vector3(...values);
const bind = (name) => v(sockets.get(name).position);
const rotation = (values = [0, 0, 0]) =>
  new Quaternion().setFromEuler(new Euler(...values));
const rest = () =>
  Object.fromEntries(
    bones.map((name) => [
      name,
      name === "arm_R"
        ? rotation([0, 0, 0.14])
        : name === "arm_L"
          ? rotation([0, 0, -0.14])
          : name.startsWith("forearm")
            ? rotation([-0.1, 0, 0])
            : new Quaternion(),
    ]),
  );
const smooth = (value) => value * value * (3 - 2 * value);
const poses = source.keys.map((key) => {
  const pose = rest();
  if (key.rest) return pose;
  pose.chest = rotation(key.chest);
  pose.head = rotation(key.head);
  const shoulder = bind("arm_R")
    .applyQuaternion(pose.chest)
    .add(bind("chest"))
    .add(bind("hips"));
  const wrist = v(key.wrist),
    reach = wrist.clone().sub(shoulder),
    distance = reach.length();
  const upper = bind("forearm_R"),
    lower = bind("hand_R");
  const a = upper.length(),
    b = lower.length();
  if (distance >= a + b - 0.006 || distance <= Math.abs(a - b) + 0.006)
    throw new Error(`Unreachable authored wrist at ${key.time}`);
  const direction = reach.normalize();
  const along = (a * a - b * b + distance * distance) / (2 * distance);
  const pole = v([1, -0.12, 0.05]);
  pole.addScaledVector(direction, -pole.dot(direction)).normalize();
  const elbow = shoulder
    .clone()
    .addScaledVector(direction, along)
    .addScaledVector(pole, Math.sqrt(a * a - along * along));
  const upperWorld = new Quaternion().setFromUnitVectors(
    upper.clone().normalize(),
    elbow.clone().sub(shoulder).normalize(),
  );
  const lowerWorld = new Quaternion().setFromUnitVectors(
    lower.clone().normalize(),
    wrist.clone().sub(elbow).normalize(),
  );
  pose.arm_R = pose.chest.clone().invert().multiply(upperWorld);
  pose.forearm_R = upperWorld.clone().invert().multiply(lowerWorld);
  const handWorld = new Quaternion().setFromUnitVectors(
    v([0, -1, 0]),
    v(key.fingers).normalize(),
  );
  pose.hand_R = lowerWorld.clone().invert().multiply(handWorld);
  // The free left hand follows a small counter-swing, with no hip/foot motion.
  pose.arm_L = rotation([-0.035, 0, -0.18]);
  return pose;
});
const frames = [];
for (let frame = 0; frame <= 144; frame++) {
  const time = frame / 60;
  let high = 1;
  while (high < source.keys.length - 1 && source.keys[high].time < time) high++;
  const a = source.keys[high - 1],
    b = source.keys[high];
  const blend = smooth((time - a.time) / (b.time - a.time));
  frames.push({
    time: +time.toFixed(7),
    root: [0, 0, 0],
    support: 0,
    rotations: bones.flatMap((name) =>
      poses[high - 1][name]
        .clone()
        .slerp(poses[high][name], blend)
        .normalize()
        .toArray()
        .map((n) => +n.toFixed(8)),
    ),
  });
}
const clip = {
  duration: source.duration,
  loop: false,
  markers: [],
  source: {
    kind: "original",
    file: "assets/source/performances/snap-salute/keyframes.json",
    license: "Original project-authored motion",
    description: source.description,
  },
  frames,
};
await fs.writeFile(
  new URL("src/snap-salute-data.ts", root),
  `// Generated by scripts/build-snap-salute.mjs from original project-authored keyframes.\n// prettier-ignore\nexport const snapSaluteData = ${JSON.stringify({ bones, clip })};\n`,
);
await fs.writeFile(
  new URL("assets/source/performances/snap-salute/baked-clip.json", root),
  JSON.stringify({ bones, clip }) + "\n",
);
console.log(
  `Baked ${frames.length} original Snap Salute frames, ${bones.length} unchanged rig bones, ${source.duration}s.`,
);
